export type Messages = typeof en;

export function messages(locale: Locale): Messages {
  return locale === "ar" ? ar : en;
}

export function greetingText(locale: Locale, date = new Date()) {
  const hour = Number(
    new Intl.DateTimeFormat("en-GB", { hour: "numeric", hourCycle: "h23", timeZone: "Asia/Riyadh" }).format(date),
  );
  const g = messages(locale).greeting;
  if (hour < 12) return g.morning;
  if (hour < 17) return g.afternoon;
  return g.evening;
}

export function relativeText(locale: Locale, value: Date | string, now = new Date()) {
  const copy = messages(locale).time;
  const diffMs = now.getTime() - new Date(value).getTime();
  const minutes = Math.round(diffMs / 60000);
  if (minutes < 1) return copy.justNow;
  if (minutes < 60) return locale === "ar" ? `قبل ${minutes} ${copy.minAgo}` : `${minutes} ${copy.minAgo}`;
  const hours = Math.round(minutes / 60);
  if (hours < 24) return locale === "ar" ? `قبل ${hours} ${copy.hrAgo}` : `${hours} ${copy.hrAgo}`;
  const days = Math.round(hours / 24);
  if (days === 1) return copy.yesterday;
  return locale === "ar" ? `قبل ${days} ${copy.daysAgo}` : `${days} ${copy.daysAgo}`;
}
